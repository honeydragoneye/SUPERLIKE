/**
 * The user manual, as data.
 *
 * Kept apart from the markup so a section is its words: the page reads this to
 * draw the table of contents and the sections, and nothing here knows how a
 * block looks. Every statement was checked against the code it describes; when
 * a screen changes, its section changes here.
 */

export type ManualBlock =
  /** a paragraph */
  | { kind: "p"; text: string; /** an address to write to, shown as a mail link under the paragraph */ mail?: string }
  /** a smaller heading inside a section */
  | { kind: "h"; text: string }
  /** a bulleted list */
  | { kind: "list"; items: string[] }
  /** numbered steps, in the order they are done */
  | { kind: "steps"; items: string[] }
  /** an aside the reader can skip: a shortcut, a reason */
  | { kind: "tip"; text: string }
  /** something that goes wrong if it is missed */
  | { kind: "warn"; text: string }
  /** a two-column table: what to press, what it does */
  | { kind: "table"; head: [string, string]; rows: [string, string][] }
  /** a conversation with the chatbot, as the reader would type it */
  | { kind: "chat"; lines: { who: "me" | "bot"; text: string }[] }
  /** a screenshot, saved under /public/manual */
  | { kind: "shot"; src: string; alt: string; caption: string; /** width / height of the saved image */ ratio: number }
  /** a question and its answer */
  | { kind: "faq"; q: string; a: string };

export type ManualSection = {
  id: string;
  title: string;
  /** one or two sentences under the title: what this part is for */
  lead: string;
  blocks: ManualBlock[];
};

